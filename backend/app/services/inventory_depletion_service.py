"""
Competitor Inventory Depletion & Stockout Forecasting Service.
Tracks inventory count movements across scrape intervals, estimates competitor sales velocity (units/day),
revenue run-rate, detects restock cycles, predicts stockout dates, and highlights merchant pricing opportunities.
"""

import logging
from datetime import datetime, timezone, timedelta
from typing import List, Dict, Any, Optional
from sqlalchemy import select, desc
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.product import Product, ProductStockHistory, ProductInventoryForecast

logger = logging.getLogger(__name__)


class InventoryDepletionService:
    """Service for computing competitor sales velocity and predicting stockouts."""

    async def record_stock_observation(
        self,
        db: AsyncSession,
        product_id: int,
        stock_quantity: Optional[int],
        in_stock: bool = True,
        recorded_at: Optional[datetime] = None
    ) -> Dict[str, Any]:
        """
        Record a new stock level observation for a product.
        Automatically detects depletions, restocks, or stockout transitions,
        and triggers a recalculation of the inventory forecast.
        """
        product = await db.get(Product, product_id)
        if not product:
            raise ValueError(f"Product {product_id} not found")

        timestamp = recorded_at or datetime.now(timezone.utc)
        if timestamp.tzinfo is None:
            timestamp = timestamp.replace(tzinfo=timezone.utc)

        # Retrieve the most recent observation
        stmt = (
            select(ProductStockHistory)
            .where(ProductStockHistory.product_id == product_id)
            .order_by(desc(ProductStockHistory.recorded_at))
            .limit(1)
        )
        res = await db.execute(stmt)
        prev = res.scalar_one_or_none()

        delta = 0
        change_type = "initial"

        if prev is not None:
            # Check availability state flip
            if not prev.in_stock and in_stock:
                change_type = "back_in_stock"
                delta = stock_quantity or 1
            elif prev.in_stock and not in_stock:
                change_type = "out_of_stock"
                delta = -(prev.stock_quantity or 0)
            elif stock_quantity is not None and prev.stock_quantity is not None:
                delta = stock_quantity - prev.stock_quantity
                if delta < 0:
                    change_type = "depletion"
                elif delta > 0:
                    change_type = "restock"
                else:
                    change_type = "unchanged"
            elif not in_stock:
                change_type = "out_of_stock"
        else:
            if not in_stock:
                change_type = "out_of_stock"

        history_entry = ProductStockHistory(
            product_id=product_id,
            stock_quantity=stock_quantity,
            in_stock=in_stock,
            delta=delta,
            change_type=change_type,
            recorded_at=timestamp,
        )
        db.add(history_entry)

        # Update product current state
        product.in_stock = in_stock
        product.stock_quantity = stock_quantity
        await db.commit()
        await db.refresh(history_entry)

        # Recalculate forecast
        forecast = await self.calculate_inventory_forecast(db, product_id)

        return {
            "history": history_entry.to_dict(),
            "forecast": forecast,
        }

    async def calculate_inventory_forecast(
        self,
        db: AsyncSession,
        product_id: int
    ) -> Dict[str, Any]:
        """
        Analyze historical observations to calculate:
        - Daily sales velocity (units/day)
        - Estimated daily revenue generated by this competitor item
        - Predicted stockout date and days until depletion
        - Risk level: 'high' (<=2d), 'medium' (<=7d), 'low' (>7d), 'out_of_stock', 'unknown'
        """
        product = await db.get(Product, product_id)
        if not product:
            raise ValueError(f"Product {product_id} not found")

        # Fetch all historical observations ordered chronologically
        stmt = (
            select(ProductStockHistory)
            .where(ProductStockHistory.product_id == product_id)
            .order_by(ProductStockHistory.recorded_at.asc())
        )
        res = await db.execute(stmt)
        history = res.scalars().all()

        now = datetime.now(timezone.utc)
        current_stock = product.stock_quantity
        is_in_stock = product.in_stock

        if not history:
            return {}

        total_units_sold = 0
        total_restocks = 0
        last_restock_date = None

        for h in history:
            if h.change_type == "depletion" and h.delta < 0:
                total_units_sold += abs(h.delta)
            elif h.change_type == "restock":
                total_restocks += 1
                last_restock_date = h.recorded_at

        # Calculate time span between first observation and now
        first_time = history[0].recorded_at
        if first_time.tzinfo is None:
            first_time = first_time.replace(tzinfo=timezone.utc)

        duration_days = max(0.1, (now - first_time).total_seconds() / 86400.0)

        # Calculate velocity
        if total_units_sold > 0:
            sales_velocity_per_day = round(total_units_sold / duration_days, 2)
        else:
            sales_velocity_per_day = 0.0

        # Estimated daily revenue
        unit_price = float(product.price or product.sale_price or 0.0)
        estimated_daily_revenue = round(sales_velocity_per_day * unit_price, 2)

        predicted_stockout_date = None
        days_until_stockout = None
        stockout_risk_level = "unknown"
        opportunity_verdict = ""

        if not is_in_stock or (current_stock is not None and current_stock <= 0):
            stockout_risk_level = "out_of_stock"
            days_until_stockout = 0.0
            opportunity_verdict = (
                "🚨 Competitor is completely Out of Stock! Prime opportunity to capture 100% of displaced "
                "customer demand by featuring your matching product prominently or adjusting ad bids."
            )
        elif current_stock is not None and current_stock > 0 and sales_velocity_per_day > 0:
            days_until_stockout = round(current_stock / sales_velocity_per_day, 1)
            predicted_stockout_date = now + timedelta(days=days_until_stockout)

            if days_until_stockout <= 2.0:
                stockout_risk_level = "high"
                opportunity_verdict = (
                    f"⚠️ High Stockout Risk: Competitor has only {current_stock} units left selling at "
                    f"~{sales_velocity_per_day} units/day. Depletion expected in ~{days_until_stockout} days "
                    f"({predicted_stockout_date.strftime('%Y-%m-%d')}). Opportunity: Prepare to raise prices or launch promotions."
                )
            elif days_until_stockout <= 7.0:
                stockout_risk_level = "medium"
                opportunity_verdict = (
                    f"⚡ Medium Stockout Risk: Competitor has ~{days_until_stockout} days of stock buffer remaining "
                    f"({current_stock} units). Depletion velocity is {sales_velocity_per_day} units/day."
                )
            else:
                stockout_risk_level = "low"
                opportunity_verdict = (
                    f"✅ Healthy Stock Buffer: Competitor has ample stock ({current_stock} units, "
                    f"~{days_until_stockout} days supply) at current velocity of {sales_velocity_per_day} units/day."
                )
        elif current_stock is not None and current_stock > 0:
            stockout_risk_level = "low"
            opportunity_verdict = (
                f"ℹ️ Competitor currently has {current_stock} units in stock with no recent depletion velocity recorded."
            )
        else:
            stockout_risk_level = "unknown"
            opportunity_verdict = "ℹ️ Gathering additional stock observations to establish depletion velocity."

        # Fetch or create forecast record
        stmt_forecast = select(ProductInventoryForecast).where(ProductInventoryForecast.product_id == product_id)
        res_fc = await db.execute(stmt_forecast)
        forecast_record = res_fc.scalar_one_or_none()

        if forecast_record is None:
            forecast_record = ProductInventoryForecast(
                product_id=product_id,
                current_stock=current_stock,
                is_in_stock=is_in_stock,
                sales_velocity_per_day=sales_velocity_per_day,
                estimated_daily_revenue=estimated_daily_revenue,
                predicted_stockout_date=predicted_stockout_date,
                days_until_stockout=days_until_stockout,
                stockout_risk_level=stockout_risk_level,
                total_units_sold=total_units_sold,
                total_restocks=total_restocks,
                last_restock_date=last_restock_date,
                opportunity_verdict=opportunity_verdict,
            )
            db.add(forecast_record)
        else:
            forecast_record.current_stock = current_stock
            forecast_record.is_in_stock = is_in_stock
            forecast_record.sales_velocity_per_day = sales_velocity_per_day
            forecast_record.estimated_daily_revenue = estimated_daily_revenue
            forecast_record.predicted_stockout_date = predicted_stockout_date
            forecast_record.days_until_stockout = days_until_stockout
            forecast_record.stockout_risk_level = stockout_risk_level
            forecast_record.total_units_sold = total_units_sold
            forecast_record.total_restocks = total_restocks
            forecast_record.last_restock_date = last_restock_date
            forecast_record.opportunity_verdict = opportunity_verdict

        await db.commit()
        await db.refresh(forecast_record)
        return forecast_record.to_dict()

    async def get_forecast(self, db: AsyncSession, product_id: int) -> Optional[Dict[str, Any]]:
        """Retrieve existing forecast or calculate if not present."""
        stmt = select(ProductInventoryForecast).where(ProductInventoryForecast.product_id == product_id)
        res = await db.execute(stmt)
        record = res.scalar_one_or_none()
        if record:
            return record.to_dict()

        # Attempt to calculate if product exists
        product = await db.get(Product, product_id)
        if product:
            return await self.calculate_inventory_forecast(db, product_id)
        return None

    async def get_stock_history(
        self,
        db: AsyncSession,
        product_id: int,
        limit: int = 50
    ) -> List[Dict[str, Any]]:
        """Retrieve chronological stock observation events."""
        stmt = (
            select(ProductStockHistory)
            .where(ProductStockHistory.product_id == product_id)
            .order_by(desc(ProductStockHistory.recorded_at))
            .limit(limit)
        )
        res = await db.execute(stmt)
        records = res.scalars().all()
        return [r.to_dict() for r in records]

    async def get_stockout_opportunities(
        self,
        db: AsyncSession,
        domain: Optional[str] = None,
        risk_level: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Find competitor products with high/medium stockout risk across catalog or domain,
        sorted by highest estimated daily revenue and shortest days to stockout.
        """
        stmt = (
            select(ProductInventoryForecast, Product)
            .join(Product, ProductInventoryForecast.product_id == Product.id)
            .where(ProductInventoryForecast.stockout_risk_level.in_(["high", "medium", "out_of_stock"]))
        )

        if domain:
            stmt = stmt.where(Product.source_domain.contains(domain.lower()))

        if risk_level and risk_level != "all":
            stmt = stmt.where(ProductInventoryForecast.stockout_risk_level == risk_level)

        stmt = stmt.order_by(
            desc(ProductInventoryForecast.estimated_daily_revenue),
            ProductInventoryForecast.days_until_stockout.asc()
        )

        res = await db.execute(stmt)
        rows = res.all()

        results = []
        for fc, prod in rows:
            d = fc.to_dict()
            d["product"] = {
                "id": prod.id,
                "name": prod.name,
                "price": float(prod.price) if prod.price else None,
                "source_domain": prod.source_domain,
                "url": prod.url,
                "image_url": prod.image_url,
                "category": prod.category,
            }
            results.append(d)

        return results


inventory_service = InventoryDepletionService()
